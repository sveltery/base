import { format, resolveConfig } from 'prettier';
import type { ApiConstant, ApiPart, ApiProp } from './api.ts';
import { ordering, sortByOrder } from './type-order.ts';
import { shortName, type TypesStub } from './types.ts';

/** A table cell: pipes escaped, and line breaks kept as `&#xA;` the way Base UI writes them. */
const cell = (value: string) => value.replace(/\|/g, '\\|').replace(/\n/g, '&#xA;');
const code = (value: string | undefined) => (value === undefined ? '-' : `\`${cell(value)}\``);

const table = (head: string[], rows: string[][]) =>
	[head, head.map(() => ':---'), ...rows].map((row) => `| ${row.join(' | ')} |`).join('\n');

function propsTable(title: string, props: ApiProp[]): string[] {
	if (!props.length) return [];
	return [
		`**${title} Props:**`,
		table(
			['Prop', 'Type', 'Default', 'Description'],
			props.map((prop) => [
				prop.name,
				code(prop.type),
				code(prop.default),
				cell(prop.description) || '-'
			])
		)
	];
}

/** Base UI writes a CSS variable's name as code, and a data attribute's as plain text. */
const CONSTANT_TABLES = {
	'Data Attributes': { column: 'Attribute', name: (name: string) => name },
	'CSS Variables': { column: 'Variable', name: code }
};

function constantsTable(
	title: string,
	label: keyof typeof CONSTANT_TABLES,
	constants: ApiConstant[]
) {
	const { column, name } = CONSTANT_TABLES[label];
	if (!constants.length) return [];
	return [
		`**${title} ${label}:**`,
		table(
			[column, 'Type', 'Description'],
			constants.map((constant) => [
				name(constant.name),
				code(constant.type),
				cell(constant.description) || '-'
			])
		)
	];
}

const jsDoc = (description: string) => {
	if (!description) return [];
	const lines = description.split('\n');
	return lines.length === 1
		? [`/** ${lines[0]} */`]
		: ['/**', ...lines.map((line) => (line ? ` * ${line}` : ' *')), ' */'];
};

/** `type AccordionRootState = { ... }`, the way Base UI's `### Root.State` section shows it. */
const stateType = (part: ApiPart) =>
	[
		'```typescript',
		`type ${part.name.replaceAll('.', '')}State = {`,
		...part.state.flatMap((member) => [
			...jsDoc(member.description),
			`${member.name}${member.required ? '' : '?'}: ${member.type};`
		]),
		'};',
		'```'
	].join('\n');

function partSection(part: ApiPart): string[] {
	const title = shortName(part.name);
	return [
		`### ${title}`,
		part.description,
		...propsTable(title, part.props),
		...constantsTable(title, 'Data Attributes', part.dataAttributes),
		...constantsTable(title, 'CSS Variables', part.cssVariables),
		`### ${title}.Props`,
		`Re-export of [${title}](#${title.toLowerCase()}) props.`,
		...(part.state.length ? [`### ${title}.State`, stateType(part)] : [])
	].filter(Boolean);
}

/** `components/csp-provider` is `Csp Provider`, as Base UI titles a `types.md`. */
const title = (route: string) =>
	route
		.split('/')
		.pop()!
		.split('-')
		.map((word) => word[0].toUpperCase() + word.slice(1))
		.join(' ');

/**
 * The `types.md` Base UI's `syncTypes` writes beside a page's `types.ts`: the API reference as
 * plain markdown, for review diffs, the `.md` twins and the staleness check.
 */
export async function typesMarkdown(route: string, stub: TypesStub, file: string): Promise<string> {
	const parts = stub.multiple
		? sortByOrder(stub.parts, ordering.namespaceParts, (part) => shortName(part.name))
		: stub.parts;
	const markdown = [
		`# ${title(route)}`,
		`[//]: types.ts '<-- Autogenerated By (do not edit the following markdown directly), run: pnpm docs:validate "${route}"'`,
		'## API Reference',
		...parts.flatMap(partSection)
	].join('\n\n');
	return format(markdown, { ...(await resolveConfig(file)), filepath: file });
}
