import { format, resolveConfig } from 'prettier';
import { objectType, type ApiConstant, type ApiPart, type ApiProp, type ApiType } from './api.ts';
import { orderedParts, shortName, type TypesStub } from './types.ts';

/** A table cell: pipes escaped, and line breaks kept as `&#xA;` the way Base UI writes them. */
const cell = (value: string) => value.replace(/\|/g, '\\|').replace(/\n/g, '&#xA;');
/** Inline code. A value with a backtick in it is fenced with two, as in `` `${'left'}` ``. */
const code = (value: string | undefined) =>
	value === undefined
		? '-'
		: value.includes('`')
			? `\`\` ${cell(value)} \`\``
			: `\`${cell(value)}\``;

const table = (head: string[], rows: string[][]) =>
	[head, head.map(() => ':---'), ...rows].map((row) => `| ${row.join(' | ')} |`).join('\n');

function propsTable(title: string, props: ApiProp[]): string[] {
	if (!props.length) return [];
	return [
		`**${title} Props:**`,
		table(
			['Prop', 'Type', 'Default', 'Description'],
			props.map((prop) => [
				prop.name,
				code(prop.type),
				code(prop.default),
				cell(prop.description) || '-'
			])
		)
	];
}

/** Base UI writes a CSS variable's name as code, and a data attribute's as plain text. */
const CONSTANT_TABLES = {
	'Data Attributes': { column: 'Attribute', name: (name: string) => name },
	'CSS Variables': { column: 'Variable', name: code }
};

function constantsTable(
	title: string,
	label: keyof typeof CONSTANT_TABLES,
	constants: ApiConstant[]
) {
	const { column, name } = CONSTANT_TABLES[label];
	if (!constants.length) return [];
	return [
		`**${title} ${label}:**`,
		table(
			[column, 'Type', 'Description'],
			constants.map((constant) => [
				name(constant.name),
				code(constant.type),
				cell(constant.description) || '-'
			])
		)
	];
}

const prettierConfig = resolveConfig(import.meta.filename);

/** A declaration formatted the way the repository formats TypeScript. */
export async function prettyCode(code: string): Promise<string> {
	return (await format(code, { ...(await prettierConfig), parser: 'typescript' })).trimEnd();
}

const typescript = async (code: string) => `\`\`\`typescript\n${await prettyCode(code)}\n\`\`\``;

/** `type AccordionRootState = { ... }`, the way Base UI's `### Root.State` section shows it. */
const stateType = (part: ApiPart) =>
	typescript(objectType(`${part.name.replaceAll('.', '')}State`, part.state));

async function partSection(part: ApiPart): Promise<string[]> {
	const title = shortName(part.name);
	return [
		`### ${title}`,
		part.description,
		...propsTable(title, part.props),
		...constantsTable(title, 'Data Attributes', part.dataAttributes),
		...constantsTable(title, 'CSS Variables', part.cssVariables),
		`### ${title}.Props`,
		`Re-export of [${title}](#${title.toLowerCase()}) props.`,
		...(part.state.length ? [`### ${title}.State`, await stateType(part)] : [])
	].filter(Boolean);
}

const CONSTANT_GROUPS = { DataAttributes: 'Data attributes', CssVariables: 'CSS variables' };

/** A constant group links the part whose table it holds, as Base UI's does. */
async function additionalSection(type: ApiType): Promise<string[]> {
	const part = type.of && shortName(type.of.part);
	return [
		`### ${type.name}`,
		part
			? `${CONSTANT_GROUPS[type.of!.kind]} of [${part}](#${part.toLowerCase()}).`
			: type.description,
		await typescript(type.code)
	].filter(Boolean);
}

/** `components/csp-provider` is `Csp Provider`, as Base UI titles a `types.md`. */
const title = (route: string) =>
	route
		.split('/')
		.pop()!
		.split('-')
		.map((word) => word[0].toUpperCase() + word.slice(1))
		.join(' ');

/**
 * The `types.md` Base UI's `syncTypes` writes beside a page's `types.ts`: the API reference as
 * plain markdown, for review diffs, the `.md` twins and the staleness check.
 */
export async function typesMarkdown(route: string, stub: TypesStub, file: string): Promise<string> {
	const markdown = [
		`# ${title(route)}`,
		`[//]: types.ts '<-- Autogenerated By (do not edit the following markdown directly), run: pnpm docs:validate "${route}"'`,
		'## API Reference',
		...(await Promise.all(orderedParts(stub).map(partSection))).flat(),
		...(stub.types.length ? ['## Additional Types'] : []),
		...(await Promise.all(stub.types.map(additionalSection))).flat(),
		...(stub.externals.length ? ['## External Types'] : []),
		...(
			await Promise.all(
				stub.externals.map(async (external) => [
					`### ${external.name}`,
					await typescript(external.code)
				])
			)
		).flat()
	].join('\n\n');
	return format(markdown, { ...(await resolveConfig(file)), filepath: file });
}
