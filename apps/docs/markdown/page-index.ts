import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { compile } from 'mdsvex';
import { mdsvexPlugins } from './headings.ts';
import { metadata, slugify, type Sections } from './metadata.ts';
import { orderedParts, pageStub, shortName } from './types.ts';

/** A part's or an export's API, as upstream's `SitemapPart` lists it. */
export type ApiSummary = { props?: string[]; dataAttributes?: string[]; cssVariables?: string[] };

/**
 * One entry of a section index: a line of its hand-edited list and, unless `skipDetailSection`,
 * a generated section. `title` is the child page's H1, and `displayTitle` the list's title when an
 * author changed it.
 */
export type IndexPage = {
	slug: string;
	path: string;
	title: string;
	displayTitle?: string;
	description?: string;
	tags?: string[];
	skipDetailSection?: boolean;
	sections?: Sections;
	parts?: Record<string, ApiSummary>;
	exports?: Record<string, ApiSummary>;
	types?: string[];
};

/** A section index page, `<section>/+page.md`. `tail` is the hand-edited markdown after the generated zone. */
export type PageIndex = { title: string; pages: IndexPage[]; tail: string };

const LIST_MARKER =
	"[//]: # 'This section is autogenerated, but the following list order, title, and [Tag]s can be modified, but nothing within the parentheses.'";
const generatedMarker = (route: string) =>
	`[//]: # 'This section is autogenerated, DO NOT EDIT AFTER THIS LINE, run: pnpm docs:validate "${route}"'`;
const END_MARKER =
	"[//]: # 'The above section is autogenerated, but the remainder of the file can be modified.'";

// Upstream keeps index pages out of search engines with `robots: { index: false }`.
const DEFAULT_TAIL = '<svelte:head>\n<meta name="robots" content="noindex" />\n</svelte:head>\n';

const SINGLE_LINK = /^- \[(.+?)\]\((\S+?)\)((?:\s*\[[^\]]+\])*)\s*$/;
const PAGE_LINE = /^- (.+?) - \(\[Outline\]\(#([^)]*)\), \[Contents\]\(([^)]+)\)\)\s*$/;
const TAG = /\s*\[([^\]]+)\]/g;

const tagsOf = (value: string) => [...value.matchAll(TAG)].map((match) => match[1]);
const escapeUnderscores = (value: string) => value.replace(/_/g, '\\_');
const unescapeUnderscores = (value: string) => value.replace(/\\_/g, '_');
export const kebabToTitle = (value: string) =>
	value
		.split('-')
		.map((word) => word[0].toUpperCase() + word.slice(1))
		.join(' ');

/** Upstream's `markdownToMetadata`, for the flat index format: the list, the generated zone and the tail. */
export function parsePageIndex(markdown: string): PageIndex {
	const lines = markdown.split('\n');
	let title = '';
	let zone: 'head' | 'list' | 'generated' = 'head';
	let tail = '';
	const pages: IndexPage[] = [];
	let page: IndexPage | undefined;
	let inDescription = false;
	// The open "- Sections:" or "- Exports:" list of the current page.
	let block: 'sections' | 'exports' | undefined;
	let stack: { level: number; children: Sections }[] = [];
	let api: ApiSummary | undefined;

	for (const [i, line] of lines.entries()) {
		if (line === LIST_MARKER) zone = 'list';
		else if (line.includes('DO NOT EDIT AFTER THIS LINE')) zone = 'generated';
		else if (line === END_MARKER) {
			tail = lines
				.slice(i + 1)
				.join('\n')
				.replace(/^\n+/, '');
			break;
		} else if (zone === 'head' && line.startsWith('# ')) title = line.slice(2).trim();
		else if (zone === 'list' && line.startsWith('- ')) pages.push(listEntry(line));
		else if (zone === 'generated') {
			const heading = /^## (.+)$/.exec(line);
			const item = /^( *)- (.*)$/.exec(line);
			if (heading) {
				const headingTitle = heading[1].trim();
				page =
					pages.find((entry) => entry.title === headingTitle) ??
					pages.find((entry) => entry.slug === slugify(headingTitle));
				if (page) page.title = headingTitle;
				inDescription = true;
				block = undefined;
			} else if (!page) continue;
			else if (inDescription) {
				if (line.trim())
					page.description = page.description ? `${page.description} ${line.trim()}` : line.trim();
				else if (page.description) inDescription = false;
			} else if (item && !item[1]) {
				const [label, value] = item[2].split(/:\s*/, 2) as [string, string | undefined];
				block = label === 'Sections' ? 'sections' : label === 'Exports' ? 'exports' : undefined;
				if (block === 'sections') {
					page.sections = {};
					stack = [{ level: 0, children: page.sections }];
				}
				if (label === 'Types' && value) page.types = value.split(',').map((type) => type.trim());
			} else if (item && block === 'sections') {
				const level = item[1].length / 2;
				const titleMarkdown = item[2].replace(/^(\d+)\\\.\s/, '$1. ');
				const sectionTitle = titleMarkdown.replace(/`/g, '');
				while (stack.at(-1)!.level >= level) stack.pop();
				const children: Sections = {};
				stack.at(-1)!.children[slugify(sectionTitle)] =
					titleMarkdown === sectionTitle
						? { title: sectionTitle, children }
						: { title: sectionTitle, titleMarkdown, children };
				stack.push({ level, children });
			} else if (item && block === 'exports' && item[1].length === 2) {
				api = {};
				const prefix = `${page.title} - `;
				if (item[2].startsWith(prefix)) (page.parts ??= {})[item[2].slice(prefix.length)] = api;
				else (page.exports ??= {})[item[2]] = api;
			} else if (item && block === 'exports' && api) {
				const [label, value = ''] = item[2].split(/:\s*/, 2);
				const names = value.split(',').map((name) => unescapeUnderscores(name.trim()));
				if (label === 'Props') api.props = names;
				else if (label === 'Data Attributes') api.dataAttributes = names;
				else if (label === 'CSS Variables') api.cssVariables = names;
			}
		}
	}
	for (const entry of pages) if (entry.displayTitle === entry.title) delete entry.displayTitle;
	return { title, pages, tail };
}

/** One line of the hand-edited list: a page with an outline, or a single link such as llms.txt. */
function listEntry(line: string): IndexPage {
	const single = SINGLE_LINK.exec(line);
	if (single) {
		const tags = tagsOf(single[3]);
		return {
			slug: slugify(single[1]),
			path: single[2],
			title: single[1],
			skipDetailSection: true,
			...(tags.length ? { tags } : {})
		};
	}
	const listed = PAGE_LINE.exec(line);
	if (!listed)
		throw new Error(
			`An index list line is "- Title - ([Outline](#slug), [Contents](./slug/+page.md))" or "- [Title](url) [Tag]": ${line}`
		);
	const tags = tagsOf(listed[1]);
	const listTitle = listed[1].replace(TAG, '').trim();
	return {
		slug: listed[2],
		path: listed[3],
		title: listTitle,
		displayTitle: listTitle,
		...(tags.length ? { tags } : {})
	};
}

const sectionLines = (sections: Sections, depth = 1): string[] =>
	Object.values(sections).flatMap((section) => [
		`${'  '.repeat(depth)}- ${(section.titleMarkdown ?? section.title).replace(/^(\d+)\.\s/, '$1\\. ')}`,
		...sectionLines(section.children, depth + 1)
	]);

const apiLines = (name: string, api: ApiSummary) => [
	`  - ${name}`,
	...(
		[
			['Props', api.props],
			['Data Attributes', api.dataAttributes],
			['CSS Variables', api.cssVariables]
		] as const
	).flatMap(([label, names]) =>
		names?.length ? [`    - ${label}: ${names.map(escapeUnderscores).join(', ')}`] : []
	)
];

/** Upstream's `metadataToMarkdown`, for a flat index. `route` names the index in the regenerate command. */
export function renderPageIndex({ title, pages, tail }: PageIndex, route: string): string {
	const tagged = (value: string, tags?: string[]) =>
		[value, ...(tags ?? []).map((tag) => `[${tag}]`)].join(' ');
	const list = pages.map((page) =>
		page.skipDetailSection
			? tagged(`- [${page.displayTitle ?? page.title}](${page.path})`, page.tags)
			: `${tagged(`- ${page.displayTitle ?? page.title}`, page.tags)} - ([Outline](#${page.slug}), [Contents](${page.path}))`
	);
	const details = pages
		.filter((page) => !page.skipDetailSection)
		.flatMap((page) => {
			const outline = [
				...(page.sections && Object.keys(page.sections).length
					? ['- Sections:', ...sectionLines(page.sections)]
					: []),
				...(page.parts || page.exports
					? [
							'- Exports:',
							...Object.entries(page.parts ?? {}).flatMap(([part, api]) =>
								apiLines(`${page.title} - ${part}`, api)
							),
							...Object.entries(page.exports ?? {}).flatMap(([name, api]) => apiLines(name, api))
						]
					: []),
				...(page.types?.length ? [`- Types: ${page.types.join(', ')}`] : [])
			];
			return [
				`## ${page.title}`,
				'',
				page.description ?? 'No description available',
				'',
				...(outline.length
					? ['<details>', '', '<summary>Outline</summary>', '', ...outline, '', '</details>', '']
					: []),
				`[Read more](${page.path})`,
				''
			];
		});
	return [
		`# ${title}`,
		'',
		LIST_MARKER,
		'',
		...list,
		'',
		generatedMarker(route),
		'',
		...details,
		END_MARKER,
		'',
		tail
	].join('\n');
}

/**
 * Upstream's `mergeMetadataPages`. The list keeps its order, titles and tags, and each listed
 * page takes its child's H1, description and outline. A child the list lacks is appended with a
 * `[New]` tag. A listed page with no child stays until someone removes it, as upstream does.
 */
export function mergePages(existing: IndexPage[], children: IndexPage[]): IndexPage[] {
	const byPath = new Map(children.map((child) => [child.path, child]));
	const merged = existing.map((page) => {
		const child = byPath.get(page.path);
		if (!child) return page;
		byPath.delete(page.path);
		const { displayTitle, tags, skipDetailSection } = page;
		return {
			...child,
			...(displayTitle && displayTitle !== child.title ? { displayTitle } : {}),
			...(tags ? { tags } : {}),
			...(skipDetailSection ? { skipDetailSection } : {})
		};
	});
	return [
		...merged,
		...[...byPath.values()].map((child) => ({ ...child, tags: [...(child.tags ?? []), 'New'] }))
	];
}

/**
 * The exports, parts and types a page documents, from the `types.ts` beside it, as upstream's
 * `updateParentIndex` writes them into the parent index.
 */
const names = (items: Array<{ name: string }>) => items.map((item) => item.name).sort();

function pageApi(file: string, lib: string): Pick<IndexPage, 'parts' | 'exports' | 'types'> {
	const stub = pageStub(file, lib);
	const parts: Record<string, ApiSummary> = {};
	const exports: Record<string, ApiSummary> = {};
	const types: string[] = [];
	for (const part of stub ? orderedParts(stub) : []) {
		const api = {
			props: names(part.props),
			dataAttributes: names(part.dataAttributes),
			cssVariables: names(part.cssVariables)
		};
		if (part.name.includes('.')) parts[shortName(part.name)] = api;
		else exports[part.name] = api;
		types.push(`${part.name}.Props`, `${part.name}.State`);
	}
	return {
		...(Object.keys(parts).length ? { parts } : {}),
		...(Object.keys(exports).length ? { exports } : {}),
		...(types.length ? { types: types.sort() } : {})
	};
}

/** Every child page of a section, as upstream's `transformMarkdownMetadata` reports it to the index. */
async function childPages(dir: string, lib: string): Promise<IndexPage[]> {
	const pages: IndexPage[] = [];
	for (const slug of readdirSync(dir).sort()) {
		const file = join(dir, slug, '+page.md');
		if (!existsSync(file)) continue;
		const source = readFileSync(file, 'utf8');
		const compiled = await compile(source, {
			smartypants: false,
			remarkPlugins: mdsvexPlugins(metadata),
			highlight: { highlighter: async () => '' },
			extensions: ['.md'],
			filename: file
		});
		const { title, subtitle, sections } = compiled!.data!.fm as {
			title: string;
			subtitle: string;
			sections: Sections;
		};
		pages.push({
			slug: slugify(title),
			path: `./${slug}/+page.md`,
			title,
			...(subtitle ? { description: subtitle } : {}),
			sections,
			...pageApi(file, lib)
		});
	}
	return pages;
}

/** The section index files under `routes`: each `<section>/+page.md` with upstream's list marker. */
export const indexFiles = (routes: string) =>
	readdirSync(routes)
		.map((section) => ({ section, file: join(routes, section, '+page.md') }))
		.filter(({ file }) => existsSync(file) && readFileSync(file, 'utf8').includes(LIST_MARKER));

/**
 * Upstream's `syncPageIndex`: regenerates a section index from its child pages, writing it when
 * it changed. Returns whether it did.
 */
export async function syncPageIndex(
	file: string,
	{ routes, lib }: { routes: string; lib: string }
): Promise<boolean> {
	const dir = join(file, '..');
	const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
	const existing = current ? parsePageIndex(current) : undefined;
	const markdown = renderPageIndex(
		{
			title: kebabToTitle(relative(routes, dir).split('/').pop()!),
			pages: mergePages(existing?.pages ?? [], await childPages(dir, lib)),
			tail: existing?.tail || DEFAULT_TAIL
		},
		relative(join(routes, '..'), dir)
	);
	const changed = markdown !== current;
	if (changed) writeFileSync(file, markdown);
	return changed;
}
