/**
 * Items in `order`'s order, with the ones it leaves out sorted by name at its `__EVERYTHING_ELSE__`
 * marker. An empty order keeps the items as declared.
 */
export function sortByOrder<T>(items: T[], order: string[], name: (item: T) => string): T[] {
	if (!order.length) return items;
	const listed = new Set(order);
	const rest = items
		.filter((item) => !listed.has(name(item)))
		.sort((a, b) => compare(name(a), name(b)));
	return order.flatMap((key) =>
		key === EVERYTHING_ELSE ? rest : items.filter((item) => name(item) === key)
	);
}

/** JavaScript's default sort, which upstream's `Object.keys(...).sort()` uses. */
export const compare = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
